sessions: Dict[str, List] = {}

def get_or_create_session(session_id: Optional[str] = None) -> str:
    if session_id and session_id in sessions:
        return session_id
    new_id = str(uuid.uuid4())
    sessions[new_id] = []
    return new_id


# ---- per-session message cap ----
# Every real turn is at least one paid API call (an LLM completion), and a
# voice turn is three (STT, LLM, TTS). This assistant has no auth and no
# other rate limiting, so without a cap a single visitor — or a bot — could
# run up real cost with no ceiling. The cap resets per browser session
# (a fresh session_id) rather than per IP, matching how sessions already
# work here; it isn't meant to survive someone deliberately clearing state,
# only to stop an ordinary spam loop from being expensive.
MAX_MESSAGES_PER_SESSION = int(os.getenv("MAX_MESSAGES_PER_SESSION", "15"))
SESSION_LIMIT_MESSAGE = (
    "That's the limit I've got set on this for now — email me directly and "
    "I'll pick it up from there: sauds6446@gmail.com"
)


def session_message_count(history: List) -> int:
    return sum(1 for m in history if isinstance(m, HumanMessage))


def session_limit_reached(history: List) -> bool:
    return session_message_count(history) >= MAX_MESSAGES_PER_SESSION


# Style overlay applied only to spoken turns. The text assistant is allowed
# to be thorough and use markdown; out loud, that same answer sounds like a
# brochure being read at you. This layer keeps the underlying knowledge and
# tools identical while changing only the delivery: short, plain, spoken.
VOICE_STYLE_PROMPT = """
YOU ARE SPEAKING OUT LOUD. Your reply is read by a text-to-speech voice, so
write it the way a calm, grounded person actually talks — not the way an
article is written.

NEVER READ A LIST ALOUD. This is the most important rule here. Spoken lists
turn into one long flat drone that nobody can follow. If the honest answer is
a list, say roughly how many there are, name two or three, and stop. Then ask
which one they want.

  Asked "tell me about his projects", DO NOT recite every project. Say
  something like: "He's got a fair few up there. A lot of it's machine
  learning and retrieval work. There's some robotics and computer vision too.
  Which of those sounds interesting?"

Length:
- Two or three sentences is normal. One is often better.
- Never go past about five sentences, no matter what was asked.
- Answer the one thing that was asked. Nothing extra. No "would you also like
  to know about...". If they want more, they'll ask.

Rhythm — this is what stops it sounding robotic:
- Short sentences. End them with a full stop.
- A long sentence strung together with commas becomes one breathless run when
  it's spoken. Break it into separate sentences instead.
- Vary the length. A short one after a longer one keeps it from droning.
- Break where a person would actually pause for breath.

Tone:
- You are still Saud, speaking in first person, exactly as everywhere else in
  this prompt. Speaking out loud changes your delivery, never your identity.
- Plain and warm. Relaxed, not peppy. Confident, not salesy. You're just a
  person answering a question about your own work, not performing.
- Use contractions: "I'm", "it's", "that's". Natural speech over correct
  written grammar.
- Never say "I'm an AI assistant". Never narrate what you're about to do.
- Don't end every single turn with a question. Sometimes just answer and
  stop — a real person doesn't say "what else would you like to know?" after
  every sentence. Vary how you leave space for the next question, and often
  leave none at all.

WHEN YOU CAN'T MAKE OUT WHAT THEY SAID:
Speech gets transcribed before it reaches you, and the transcription is
sometimes wrong — especially on names. If a message is garbled, nonsensical,
or a single word you don't recognise, do NOT treat it as an off-topic question
and do NOT give the redirect line. Just say you didn't catch that and ask them
to say it again. Something like "Sorry, I didn't catch that — say it again?"

If a message is mostly clear but contains one odd-sounding name, assume it's a
mangled version of something you actually know rather than an unfamiliar
company. "Cotro Globe", "Kauter Global" and "Gator Global" are all COTER
Global. "Overlaps" is Oval Labs. Answer the question they meant to ask, and
it's fine to gently confirm the name as you do.

Never write:
- Any markdown. No asterisks, headers, bullets, numbered lists, links, code
  blocks. It all gets read out as literal noise.
- Emoji, arrows, or special symbols.
- URLs or file paths spelled out. Say "it's on the projects page" instead.
- A run of numbers. Pick the one figure that matters and say only that.

If the question is vague, ask one short question back rather than guessing at
a long answer.
""".strip()


def build_messages(history: List, voice: bool = False) -> List[dict]:
    current_system_prompt = load_system_prompt()
    project_index_text = format_project_index(load_projects_data()["index"])

    # The model otherwise has zero knowledge that a cap exists at all, so if
    # asked "how many questions do I have left?" it just guesses — usually
    # "unlimited" — which is exactly the kind of invented answer the rest of
    # this prompt tells it never to give. Telling it the real number lets it
    # answer honestly instead. `history` already includes this turn's own
    # HumanMessage by the time build_messages runs (every call site appends
    # before calling this), so the count below already reflects "after this
    # message" correctly.
    remaining = max(0, MAX_MESSAGES_PER_SESSION - session_message_count(history))
    session_limit_text = (
        f"SESSION LIMIT (factual, not for you to bring up unprompted): this chat is "
        f"capped at {MAX_MESSAGES_PER_SESSION} messages per browser session to keep "
        f"API costs bounded. {remaining} message(s) remain after this one. If asked "
        f"how many questions/messages are left, or whether there's a limit at all, "
        f"answer with this exact number honestly — never say it's unlimited or that "
        f"you don't know. Once the cap is reached, the app automatically shows a "
        f"message pointing to sauds6446@gmail.com; you don't need to mention that "
        f"yourself unless asked."
    )

    full_system = (
        f"{current_system_prompt}\n\n---\n\n{session_limit_text}\n\n---\n\n{SITE_MAP}\n\n---\n\n{project_index_text}"
    )
    if voice:
        full_system = f"{full_system}\n\n---\n\n{VOICE_STYLE_PROMPT}"
    messages = [{"role": "system", "content": full_system}]
    for msg in history:
        if isinstance(msg, HumanMessage):
            messages.append({"role": "user", "content": msg.content})
        elif isinstance(msg, AIMessage):
            messages.append({"role": "assistant", "content": msg.content})
    return messages


