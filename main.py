def _strip_markdown_for_speech(text: str) -> str:
    """Belt-and-braces cleanup before TTS. The voice prompt already asks the
    model not to emit markdown, but if any slips through, these characters get
    read out as literal noise ("star star", "hash"), which instantly breaks
    the illusion of a person talking. Cheap to run, so we always run it."""
    import re

    cleaned = text
    cleaned = re.sub(r"```.*?```", " ", cleaned, flags=re.DOTALL)   # code fences
    cleaned = re.sub(r"`([^`]*)`", r"\1", cleaned)                  # inline code
    cleaned = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", cleaned)    # links/images
    cleaned = re.sub(r"^\s{0,3}#{1,6}\s*", "", cleaned, flags=re.MULTILINE)  # headers
    cleaned = re.sub(r"^\s*[-*+•▸◈]\s+", "", cleaned, flags=re.MULTILINE)    # bullets
    cleaned = re.sub(r"^\s*\d+[.)]\s+", "", cleaned, flags=re.MULTILINE)     # numbered
    cleaned = re.sub(r"(\*\*|__|\*|_)", "", cleaned)                # emphasis
    cleaned = re.sub(r"^\s*>\s?", "", cleaned, flags=re.MULTILINE)  # quotes
    cleaned = re.sub(r"[ \t]+", " ", cleaned)
    cleaned = re.sub(r"\n{2,}", "\n", cleaned)
    return cleaned.strip()


def _shape_for_speech(text: str) -> str:
    """Give the TTS engine something to breathe against.

    Every TTS model paces off punctuation and line breaks. A reply that comes
    back as one dense paragraph therefore gets read as one dense paragraph —
    which is the "it just talks in a single flow" problem. Putting each
    sentence on its own line converts the model's sentence boundaries into
    actual audible pauses, and splitting on semicolons/dashes breaks up the
    long comma-chains that otherwise get read without stopping."""
    import re

    text = _strip_markdown_for_speech(text)
    # Semicolons and dashes are written punctuation; spoken, they're just
    # full stops. Converting them creates a real pause instead of a glide.
    text = re.sub(r"\s*[;—–]\s*", ". ", text)
    text = re.sub(r"\s*:\s*", ". ", text)
    # Those replacements leave a lowercase word after the new full stop, which
    # would stop the sentence splitter below from seeing a boundary there.
    text = re.sub(r"([.!?]\s+)([a-z])", lambda m: m.group(1) + m.group(2).upper(), text)
    # One sentence per line. The uppercase lookahead keeps decimals and common
    # abbreviations ("3.5", "e.g.") from being split into odd little gaps.
    text = re.sub(r"(?<=[.!?])\s+(?=[A-Z])", "\n", text)
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    return "\n".join(lines)


# Proper nouns the transcriber has no way to guess phonetically. Without this,
# "COTER Global" came back as "Cotro Globe", "Kauter Global" and "Gator
# Global" in a single conversation, and "Oval Labs" became "overlaps" — which
# then made the assistant think it was being asked about unrelated companies
# and refuse to answer. The API takes this as a vocabulary hint.
STT_VOCABULARY = (
    "This is a conversation with Saud Ahmad, an AI engineer. Expect these names: "
    "Saud Ahmad, COTER Global, Oval Labs, Nebula, Centauri, ZYP Technologies, "
    "TrueSight, AgroBot, Access Vision, HSE Performance Tracker, SmartNest, "
    "GIK Institute, Swat, Pakistan. Technical terms: RAG, retrieval augmented "
    "generation, LLM, LoRA, QLoRA, fine-tuning, embeddings, FAISS, LangChain, "
    "LangGraph, PyTorch, YOLOv8, CLIP, diffusion, GAN, agentic AI, FastAPI, React."
)


# Whisper-family models are trained to continue the `prompt` text, not just be
# biased by it. When a clip contains no intelligible speech (silence, room
# noise, a stray tap, a mic that opened and closed), the model has nothing to
# transcribe and its most likely continuation is the prompt itself — so it
# returns STT_VOCABULARY back verbatim, or a chunk of it. Without this guard
# that echo becomes the "transcript": it renders as the visitor's own caption
# in the UI and gets appended to history as a real user message, which is why
# the assistant then starts answering a prompt dump instead of a question.
#
# Same clip conditions also produce the well-known fixed hallucinations below
# (artifacts of the model's training data — subtitle corpora full of these).
_STT_HALLUCINATIONS = {
    "thank you", "thanks for watching", "thanks for watching!",
    "thank you for watching", "thank you very much", "you", "bye",
    "please subscribe", "subscribe to my channel", "okay", "ok",
    ".", "..", "...", "!", "?",
}


def _normalize_for_compare(text: str) -> str:
    """Lowercase, strip punctuation, collapse whitespace — so an echo that
    differs only in casing or trailing punctuation still matches."""
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower()).split())


_STT_VOCAB_NORMALIZED = _normalize_for_compare(STT_VOCABULARY)
_STT_VOCAB_WORDS = set(_STT_VOCAB_NORMALIZED.split())


def _is_prompt_echo_or_noise(text: str) -> bool:
    """True when the transcript isn't real speech and must be discarded.

    Deliberately conservative: a real question from a visitor will naturally
    contain words that AREN'T in the vocabulary prompt ("what", "how", "tell
    me about"), so requiring a very high overlap ratio means a genuine
    question that happens to mention COTER Global or RAG is never dropped.
    """
    normalized = _normalize_for_compare(text)
    if not normalized:
        return True

    if normalized in _STT_HALLUCINATIONS:
        return True

    words = normalized.split()

    # Direct echo: the model returned the prompt, or a contiguous slice of it.
    # Gated on length because this is a substring test, and short utterances
    # produce false positives against a long prompt — "hi" is a substring of
    # "t-hi-s", so an unguarded check would silently swallow a real greeting.
    # A genuine echo is never this short; short noise is covered above.
    if len(words) >= 6 and (
        normalized in _STT_VOCAB_NORMALIZED or _STT_VOCAB_NORMALIZED in normalized
    ):
        return True

    # Partial/reordered echo. Only applied to long transcripts — a short reply
    # like "RAG and LoRA?" is legitimately ~100% vocabulary words, so scoring
    # it this way would wrongly discard it. Real spoken questions of this
    # length always carry filler and question words from outside the prompt.
    if len(words) >= 12:
        overlap = sum(1 for w in words if w in _STT_VOCAB_WORDS) / len(words)
        if overlap >= 0.85:
            return True

    return False


def _transcribe(filename: str, audio_bytes: bytes, content_type: str) -> str:
    """STT with the same graceful downgrade as TTS — a slower transcription is
    much better than a dead turn if the faster model isn't on this account.

    Returns "" for anything that isn't real speech, so every caller's existing
    empty-transcript path handles it (no new failure mode to wire up).
    """
    def _run(model: str) -> str:
        result = openai_client.audio.transcriptions.create(
            model=model,
            file=(filename, audio_bytes, content_type),
            prompt=STT_VOCABULARY,
        )
        return (result.text or "").strip()

    try:
        text = _run(VOICE_STT_MODEL)
    except Exception as e:
        print(f"⚠️ {VOICE_STT_MODEL} unavailable ({type(e).__name__}: {e}); falling back to whisper-1")
        text = _run("whisper-1")

    if _is_prompt_echo_or_noise(text):
        print(f"🔇 discarded non-speech transcript: {text[:80]!r}")
        return ""

    return text


def _synthesize_speech(text: str) -> bytes:
    """TTS with a graceful downgrade. The instruction-steerable model is the
    whole point (it's what makes the delivery stop being monotone), but if the
    account or SDK version doesn't support it, a flat reply is still far better
    than a failed turn."""
    try:
        speech = openai_client.audio.speech.create(
            model=VOICE_TTS_MODEL,
            voice=VOICE_TTS_VOICE,
            input=text,
            instructions=VOICE_TTS_INSTRUCTIONS,
        )
        return speech.read()
    except Exception as e:
        print(f"⚠️ {VOICE_TTS_MODEL} unavailable ({type(e).__name__}: {e}); falling back to {VOICE_TTS_FALLBACK_MODEL}")
        speech = openai_client.audio.speech.create(
            model=VOICE_TTS_FALLBACK_MODEL,
            voice=VOICE_TTS_VOICE,
            input=text,
        )
        return speech.read()


# Same assistant as /chat, just with a spoken front-end: an uploaded audio
# clip is transcribed (Whisper), run through the exact same session/history/
# tool-calling logic as text chat, then the reply is synthesized back to
# speech (OpenAI TTS). Session IDs are shared with /chat and /chat/stream —
# a conversation can move between typing and talking without losing context.
@app.post("/api/voice/chat")
async def voice_chat(audio: UploadFile = File(...), session_id: Optional[str] = None):
    if not OPENAI_API_KEY:
        raise HTTPException(status_code=500, detail="OPENAI_API_KEY is not set on the server")

    # Every stage here blocks on the one before it, so the turn's latency is
    # the sum of all of them. Timing each stage separately is the only way to
    # know which one to actually attack — the timings ride back in the
    # response so the browser console shows them too, not just server logs.
    t0 = time.perf_counter()
    timings: Dict[str, int] = {}

    def mark(stage: str, since: float) -> float:
        now = time.perf_counter()
        timings[stage] = int((now - since) * 1000)
        return now

    try:
        # Checked against the session BEFORE the clip is even read, let alone
        # transcribed — a capped session triggers zero OpenAI calls (no STT,
        # no LLM, no TTS), which is the entire point of checking this early.
        sid = get_or_create_session(session_id)
        history = sessions[sid]
        if session_limit_reached(history):
            return {
                "session_id": sid,
                "transcript": "",
                "response": SESSION_LIMIT_MESSAGE,
                "audio_base64": None,
                "audio_mime": None,
                "timings": {},
            }

        audio_bytes = await audio.read()
        if not audio_bytes:
            raise HTTPException(status_code=400, detail="Empty audio upload")
        t = mark("upload_read", t0)

        # Whisper needs a filename with a real extension to infer format —
        # browsers usually send webm/ogg from MediaRecorder.
        filename = audio.filename or "clip.webm"
        user_text = _transcribe(filename, audio_bytes, audio.content_type or "audio/webm")
        t = mark("stt", t)
        if not user_text:
            # Same non-event as in the streaming endpoint: nothing intelligible
            # in the clip. Return a benign empty turn rather than a 400 so the
            # client can just go back to listening, and append nothing to
            # history.
            return {
                "session_id": sid,
                "transcript": "",
                "response": "",
                "audio_base64": None,
                "audio_mime": None,
                "no_speech": True,
                "timings": timings,
            }

        # Identical path to /chat from here on — same session store, same
        # build_messages/run_chat_completion, same tool-calling loop.
        history.append(HumanMessage(content=user_text))

        # voice=True swaps in the spoken-delivery style overlay, and the
        # tighter token ceiling is a hard backstop in case the model ignores it.
        messages = build_messages(history, voice=True)
        reply_text = run_chat_completion(messages, max_tokens=220)
        t = mark("llm", t)

        history.append(AIMessage(content=reply_text))
        sessions[sid] = history

        audio_reply_bytes = _synthesize_speech(_shape_for_speech(reply_text))
        t = mark("tts", t)

        audio_b64 = base64.b64encode(audio_reply_bytes).decode("ascii")
        mark("encode", t)
        timings["total"] = int((time.perf_counter() - t0) * 1000)

        print(
            "🎙️ voice turn "
            + "  ".join(f"{k}={v}ms" for k, v in timings.items())
            + f"  audio={len(audio_reply_bytes) // 1024}KB"
        )

        return {
            "session_id": sid,
            "transcript": user_text,
            "response": reply_text,
            "audio_base64": audio_b64,
            "audio_mime": "audio/mpeg",
            "timings": timings,
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"{type(e).__name__}: {e}")


# ---- streaming voice turn ----------------------------------------------
# The non-streaming endpoint above is strictly sequential: you don't hear the
# first word until the last word has been generated, synthesized and
# transferred. This one pipelines instead — the LLM is streamed, and the
# moment a complete sentence exists it goes straight to TTS and out to the
# browser while the rest of the reply is still being written. The client plays
# chunks from a queue, so the perceived wait becomes roughly "first sentence"
# instead of "whole turn".
#
# Later sentences are synthesized while the browser is busy playing the
# earlier ones, so their TTS time is hidden entirely.

# The first chunk is flushed as small as possible (latency is all that matters
# there). Later chunks are grouped up to this size, because a TTS call has
# fixed overhead and lots of tiny calls would stutter the delivery.
VOICE_CHUNK_MIN_CHARS = 60


def _pop_sentences(buffer: str):
    """Pull every complete sentence off the front of a growing buffer.

    The `(?=\\s|$)` lookahead is what stops "92.68" or "e.g." from being
    treated as a sentence end — a real terminator is followed by whitespace,
    a decimal point is followed by a digit."""
    import re

    out = []
    while True:
        m = re.search(r"[.!?](?=\s|$)", buffer)
        if not m:
            break
        idx = m.end()
        sentence = buffer[:idx].strip()
        buffer = buffer[idx:].lstrip()
        if sentence:
            out.append(sentence)
    return out, buffer


@app.post("/api/voice/chat/stream")
async def voice_chat_stream(audio: UploadFile = File(...), session_id: Optional[str] = None):
    t0 = time.perf_counter()

    setup_error = None
    user_text = ""
    sid = None
    messages = None
    history = None
    stt_ms = 0
    limit_hit = False
    no_speech = False

    # Session lookup and the limit check happen before anything else,
    # including reading the uploaded clip — a capped session is turned away
    # before it can trigger a single OpenAI call (no STT, no LLM, no TTS).
    # Transcription itself genuinely can't be pipelined with the rest —
    # there's nothing to say until we know what was asked — so once past
    # the cap check it happens up front, before the response starts
    # streaming.
    try:
        if not OPENAI_API_KEY:
            raise RuntimeError("OPENAI_API_KEY is not set on the server")

        sid = get_or_create_session(session_id)
        history = sessions[sid]
        if session_limit_reached(history):
            limit_hit = True
        else:
            audio_bytes = await audio.read()
            if not audio_bytes:
                raise RuntimeError("Empty audio upload")
            filename = audio.filename or "clip.webm"
            user_text = _transcribe(filename, audio_bytes, audio.content_type or "audio/webm")
            stt_ms = int((time.perf_counter() - t0) * 1000)
            if not user_text:
                # Not an error — the VAD just sent a clip with nothing
                # intelligible in it (silence, a cough, background noise, or a
                # transcript we discarded as prompt echo). Signalling this
                # distinctly lets the client drop straight back to listening
                # instead of showing a scary failure for a non-event. Nothing
                # is appended to history, so it doesn't burn a capped message
                # or pollute the conversation.
                no_speech = True
            else:
                history.append(HumanMessage(content=user_text))
                messages = build_messages(history, voice=True)
    except Exception as e:
        setup_error = f"{e}"
        print(f"❌ voice_chat_stream setup failed: {type(e).__name__}: {e}")

    def generate():
        if setup_error:
            yield f"data: {json.dumps({'type': 'error', 'error': setup_error})}\n\n"
            return

        if limit_hit:
            yield f"data: {json.dumps({'type': 'session', 'session_id': sid})}\n\n"
            yield f"data: {json.dumps({'type': 'text', 'content': SESSION_LIMIT_MESSAGE})}\n\n"
            yield f"data: {json.dumps({'type': 'done', 'response': SESSION_LIMIT_MESSAGE, 'stt_ms': 0, 'first_audio_ms': None, 'total_ms': int((time.perf_counter() - t0) * 1000)})}\n\n"
            return

        if no_speech:
            yield f"data: {json.dumps({'type': 'session', 'session_id': sid})}\n\n"
            yield f"data: {json.dumps({'type': 'no_speech'})}\n\n"
            return

        yield f"data: {json.dumps({'type': 'session', 'session_id': sid})}\n\n"
        yield f"data: {json.dumps({'type': 'transcript', 'text': user_text, 'stt_ms': stt_ms})}\n\n"

        full_text = ""
        buffer = ""
        pending = ""
        chunk_index = 0
        first_audio_at = None

        def emit_chunk(text_chunk: str, index: int):
            """Synthesize one chunk and hand it to the browser."""
            spoken = _shape_for_speech(text_chunk)
            if not spoken:
                return None
            audio_bytes_out = _synthesize_speech(spoken)
            return {
                "type": "audio",
                "index": index,
                "audio_base64": base64.b64encode(audio_bytes_out).decode("ascii"),
                "mime": "audio/mpeg",
            }

        try:
            for event in stream_chat_completion(messages, max_tokens=220):
                if event["type"] != "content" or not event["content"]:
                    continue
                full_text += event["content"]
                buffer += event["content"]

                sentences, buffer = _pop_sentences(buffer)
                for sentence in sentences:
                    pending = f"{pending} {sentence}".strip() if pending else sentence
                    # First chunk goes out immediately — that's the whole
                    # point. After that, group so we're not making a TTS
                    # call per three-word sentence.
                    if chunk_index == 0 or len(pending) >= VOICE_CHUNK_MIN_CHARS:
                        # Text first so captions stay ahead of the audio.
                        yield f"data: {json.dumps({'type': 'text', 'content': pending})}\n\n"
                        payload = emit_chunk(pending, chunk_index)
                        if payload:
                            if first_audio_at is None:
                                first_audio_at = int((time.perf_counter() - t0) * 1000)
                                payload["first_audio_ms"] = first_audio_at
                            yield f"data: {json.dumps(payload)}\n\n"
                            chunk_index += 1
                        pending = ""

            # Whatever's left when the model stops: the trailing partial
            # sentence plus any grouped text that never hit the size floor.
            tail = f"{pending} {buffer}".strip()
            if tail:
                yield f"data: {json.dumps({'type': 'text', 'content': tail})}\n\n"
                payload = emit_chunk(tail, chunk_index)
                if payload:
                    if first_audio_at is None:
                        first_audio_at = int((time.perf_counter() - t0) * 1000)
                        payload["first_audio_ms"] = first_audio_at
                    yield f"data: {json.dumps(payload)}\n\n"

            history.append(AIMessage(content=full_text))
            sessions[sid] = history

            total_ms = int((time.perf_counter() - t0) * 1000)
            print(f"🎙️ voice stream stt={stt_ms}ms first_audio={first_audio_at}ms total={total_ms}ms")
            yield f"data: {json.dumps({'type': 'done', 'response': full_text, 'stt_ms': stt_ms, 'first_audio_ms': first_audio_at, 'total_ms': total_ms})}\n\n"

        except Exception as e:
            import traceback
            traceback.print_exc()
            err = f"{type(e).__name__}: {e}"
            print(f"❌ voice_chat_stream generation failed: {err}")
            yield f"data: {json.dumps({'type': 'error', 'error': err})}\n\n"

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "Connection": "keep-alive", "X-Accel-Buffering": "no"},
    )


